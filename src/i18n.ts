const MM_DIGITS = '၀၁၂၃၄၅၆၇၈၉';

const SCAN_FORMAT_LABELS: Record<string, string> = {
  qr: 'QR',
  ean13: 'EAN-13',
  ean8: 'EAN-8',
  upc_a: 'UPC-A',
  upc_e: 'UPC-E',
  code128: 'Code 128',
};

export const scanFormatLabel = (type: string): string => SCAN_FORMAT_LABELS[type] ?? type.toUpperCase();

export const toMM = (value: number | string): string =>
  String(value).replace(/[0-9]/g, (d) => MM_DIGITS[Number(d)]);

export const formatKyat = (value: number): string =>
  `${toMM(Math.round(value).toLocaleString('en-US'))} ကျပ်`;

const MONTHS_MM = [
  'ဇန်နဝါရီ', 'ဖေဖော်ဝါရီ', 'မတ်', 'ဧပြီ', 'မေ', 'ဇွန်',
  'ဇူလိုင်', 'သြဂုတ်', 'စက်တင်ဘာ', 'အောက်တိုဘာ', 'နိုဝင်ဘာ', 'ဒီဇင်ဘာ',
];

export const parseDbDate = (createdAt: string): Date =>
  new Date(createdAt.replace(' ', 'T') + 'Z');

export const formatDateMM = (d: Date): string =>
  `${toMM(d.getDate())} ${MONTHS_MM[d.getMonth()]} ${toMM(d.getFullYear())}`;

export const formatTimeMM = (d: Date): string =>
  `${toMM(String(d.getHours()).padStart(2, '0'))}:${toMM(String(d.getMinutes()).padStart(2, '0'))}`;

export const formatDateTimeMM = (createdAt: string): string => {
  const d = parseDbDate(createdAt);
  return `${formatDateMM(d)} · ${formatTimeMM(d)}`;
};
